/**
 * Safe Translation Lookup Helper with Dev-Mode Missing Key Warning & English Fallback
 */
export function getTranslation(lang: Language, key: keyof UIStrings): string {
  const dict = TRANSLATIONS[lang];
  if (dict && dict[key]) {
    return dict[key];
  }
  if (import.meta.env && import.meta.env.DEV) {
    console.warn(`[i18n Missing Key Warning] Key '${String(key)}' missing for language '${lang}'. Falling back to English.`);
  }
  return TRANSLATIONS.en[key] || String(key);
}
